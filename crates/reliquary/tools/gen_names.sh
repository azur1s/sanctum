#!/bin/sh
# Usage: gen_names.sh <wit dir> > names.rs
W="$1"
# emit_fn <file> <enum name> <rust fn> <rust type>
emit_fn() {
  echo ""
  echo "pub fn $3(name: &str) -> Option<$4> {"
  echo "    Some(match name.strip_prefix(\"minecraft:\").unwrap_or(name) {"
  awk -v e="enum $2 {" '
    index($0, e) { on = 1; next }
    on && /}/ { on = 0 }
    on && /^[ \t]*[a-z0-9-]+,[ \t]*$/ {
      gsub(/[ \t,]/, ""); kebab = $0
      n = split(kebab, parts, "-"); camel = ""
      for (i = 1; i <= n; i++) camel = camel toupper(substr(parts[i], 1, 1)) substr(parts[i], 2)
      snake = kebab; gsub(/-/, "_", snake)
      printf "        \"%s\" => %s::%s,\n", snake, T, camel
    }' T="$4" "$W/$1"
  echo "        _ => return None,"
  echo "    })"
  echo "}"
}
echo "//! Generated by gen_names.sh from the Pumpkin WIT files. Do not edit by hand."
echo "//! Maps snake_case Minecraft ids (\"end_rod\", \"minecraft:end_rod\") to API enums."
echo ""
echo "use pumpkin_plugin_api::{DamageType, particles::Particle, wit::pumpkin::plugin::status_effect::StatusEffectType};"
emit_fn particles.wit particle particle Particle
emit_fn damage-types.wit damage-type damage_type DamageType
emit_fn status-effect.wit status-effect-type status_effect StatusEffectType
